"""F15: upload de PDF indexa o texto das páginas, não os bytes do arquivo."""

from __future__ import annotations

import pytest

from app.knowledge.extract import UnreadableDocumentError, extract_text


def _pdf(text: str) -> bytes:
    stream = f"BT /F1 12 Tf 72 720 Td ({text}) Tj ET".encode()
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R"
        b" /Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, o in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + o + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def test_pdf_returns_page_text():
    text = extract_text(_pdf("marcador de ingestao"), "pdf")
    assert "marcador de ingestao" in text
    assert "%PDF" not in text and "endobj" not in text


def test_text_formats_are_decoded():
    assert extract_text("olá".encode(), "md") == "olá"


def test_unreadable_pdf_rejected():
    with pytest.raises(UnreadableDocumentError):
        extract_text(b"not a pdf at all", "pdf")
